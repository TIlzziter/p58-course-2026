import pytest
from conftest import board_from
from connect4 import winner, winning_line

CASES = {
    "horizontal": ("""
        .......
        .......
        .......
        .......
        .......
        ...xxxx""", 1, [(5, 3), (5, 4), (5, 5), (5, 6)]),
    "vertical": ("""
        .......
        .......
        o......
        o......
        o......
        o.xxx..""", 2, [(2, 0), (3, 0), (4, 0), (5, 0)]),
    "diag_down_right": ("""
        .......
        .......
        x......
        ox.....
        oox....
        ooox...""", 1, [(2, 0), (3, 1), (4, 2), (5, 3)]),
    "diag_down_left": ("""
        .......
        .......
        ......o
        .....ox
        ....oxx
        ...oxxx""", 2, [(2, 6), (3, 5), (4, 4), (5, 3)]),
}


@pytest.mark.parametrize("name", CASES)
def test_lines(name):
    text, who, cells = CASES[name]
    b = board_from(text)
    assert winner(b) == who
    assert winning_line(b) == cells


def test_three_is_not_win():
    b = board_from("""
        .......
        .......
        .......
        x......
        x......
        xooo...""")
    assert winner(b) == 0 and winning_line(b) == []


def test_edge_no_wraparound():
    b = board_from("""
        .......
        .......
        .......
        .......
        x......
        ....xxx""")
    assert winner(b) == 0
