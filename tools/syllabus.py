@dataclass
class Lesson:
    num: int            # сквозной номер урока 1..58
    week: int
    part: int           # 1 — лекция, 2 — семинар
    slug: str
    title: str
    goals: list[str]
    homework: str
    lab: str | None = None
    contest: str | None = None
    agent: str = ""
    practice: list[str] = field(default_factory=list)  # практические задания на уроке
    intro: str = ""     # вступление в README урока (Markdown, между ссылками на слайды и «Целями»); пусто — нет
    date: dt.date | None = None         # дата урока — считается из расписания, см. assign_dates()
    due: dt.date | None = None          # срок ДЗ — начало следующего урока (None — срока нет)

    @property
    def dir(self) -> str:
        return f"w{self.week:02d}-l{self.part:02d}-{self.slug}"

    @property
    def kind(self) -> str:
        return "Лекция" if self.part == 1 else "Семинар"

    @property
    def deck(self) -> str:
        return "lecture" if self.part == 1 else "seminar"


@dataclass
class Week:
    n: int
    tri: str
    result: str
    lessons: list[Lesson] = field(default_factory=list)

    @property
    def dates(self) -> str:
        """Даты уроков недели: «03.11–06.11»; если между уроками каникулы — «22.12 и 12.01»."""
        a, b = self.lessons[0].date, self.lessons[-1].date
        sep = " и " if (b - a).days > 7 else "–"
        return f"{a:%d.%m}{sep}{b:%d.%m}"


W: list[Week] = []
_num = 0


def week(n, tri, result, l1, l2):
    global _num
    w = Week(n, tri, result)
    for part, spec in ((1, l1), (2, l2)):
        _num += 1
        w.lessons.append(Lesson(num=_num, week=n, part=part, **spec))
    W.append(w)


