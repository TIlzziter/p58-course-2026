def in_break(d: dt.date) -> bool:
    return any(a <= d <= b for a, b, _ in BREAKS)


def lesson_dates():
    """Бесконечная последовательность дат уроков: вт и пт с FIRST_LESSON, без каникул."""
    d = FIRST_LESSON
    while True:
        if d.weekday() in LESSON_WEEKDAYS and not in_break(d):
            yield d
        d += dt.timedelta(days=1)


def fmt_day(d: dt.date) -> str:
    """«вт 03.11»."""
    return f"{WEEKDAYS_RU[d.weekday()]} {d:%d.%m}"


def fmt_full(d: dt.date) -> str:
    """«вт 03.11.2026, 20:00–22:00 МСК»."""
    return f"{WEEKDAYS_RU[d.weekday()]} {d:%d.%m.%Y}, {LESSON_TIME}"


