from __future__ import annotations

from dataclasses import dataclass, field

TRIMESTERS = {"t1": "Триместр 1", "t2": "Триместр 2", "t3": "Триместр 3"}


@dataclass
class Lesson:
    num: int            # сквозной номер урока 1..58
    week: int
    part: int           # 1 — лекция, 2 — семинар
    slug: str
    title: str
    goals: list[str]
    homework: str
    lab: str | None = None
    contest: str | None = None
    agent: str = ""

    @property
    def dir(self) -> str:
        return f"w{self.week:02d}-l{self.part:02d}-{self.slug}"

    @property
    def kind(self) -> str:
        return "Лекция" if self.part == 1 else "Семинар"

    @property
    def deck(self) -> str:
        return "lecture" if self.part == 1 else "seminar"


@dataclass
class Week:
    n: int
    tri: str
    dates: str
    result: str
    lessons: list[Lesson] = field(default_factory=list)


W: list[Week] = []
_num = 0


def week(n, tri, dates, result, l1, l2):
    global _num
    w = Week(n, tri, dates, result)
    for part, spec in ((1, l1), (2, l2)):
        _num += 1
        w.lessons.append(Lesson(num=_num, week=n, part=part, **spec))
    W.append(w)


